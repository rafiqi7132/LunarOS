/* ─────────────────────────────────────────────
   fb_init()
   ───────────────────────────────────────────── */
int fb_init(void) {
    fb_addr  = (uint32_t *)FB_BASE;
    fb_w     = FB_WIDTH;
    fb_h     = FB_HEIGHT;
    fb_pitch = FB_PITCH;

    fb_clear(LUNAR_BG);
    fb_console_init();

    pl011_puts("[FB] Framebuffer initialized ");
    pl011_print_uint(fb_w);
    pl011_puts("x");
    pl011_print_uint(fb_h);
    pl011_puts(" @");
    pl011_print_hex(FB_BASE);
    pl011_puts("\n");

    return 0;
}

void fb_get_info(fb_info_t *info) {
    if (!info) return;
    info->addr  = fb_addr;
    info->width = fb_w;
    info->height = fb_h;
    info->pitch  = fb_pitch;
    info->bpp    = FB_BPP;
}

/* ─────────────────────────────────────────────
   Pixel
   ───────────────────────────────────────────── */
void fb_put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= fb_w || y >= fb_h) return;
    fb_addr[y * (fb_pitch / 4) + x] = color;
}

uint32_t fb_get_pixel(uint32_t x, uint32_t y) {
    if (x >= fb_w || y >= fb_h) return 0;
    return fb_addr[y * (fb_pitch / 4) + x];
}

/* ─────────────────────────────────────────────
   Screen
   ───────────────────────────────────────────── */
void fb_clear(uint32_t color) {
    uint32_t total = (fb_pitch / 4) * fb_h;
    for (uint32_t i = 0; i < total; i++) fb_addr[i] = color;
}

void fb_scroll_up(uint32_t lines) {
    uint32_t pixels_per_line = lines * FONT_H * (fb_pitch / 4);
    uint32_t total = (fb_pitch / 4) * fb_h;

    /* Geser pixel ke atas */
    for (uint32_t i = 0; i < total - pixels_per_line; i++) {
        fb_addr[i] = fb_addr[i + pixels_per_line];
    }
    /* Bersihkan baris bawah */
    for (uint32_t i = total - pixels_per_line; i < total; i++) {
        fb_addr[i] = con_bg;
    }
}

/* ─────────────────────────────────────────────
   Shape
   ───────────────────────────────────────────── */
void fb_fill_rect(uint32_t x, uint32_t y,
                  uint32_t w, uint32_t h, uint32_t color)
{
    for (uint32_t row = y; row < y + h && row < fb_h; row++)
        for (uint32_t col = x; col < x + w && col < fb_w; col++)
            fb_put_pixel(col, row, color);
}

void fb_draw_rect(uint32_t x, uint32_t y,
                  uint32_t w, uint32_t h,
                  uint32_t color, uint32_t t)
{
    fb_fill_rect(x,         y,         w, t, color);   /* atas */
    fb_fill_rect(x,         y+h-t,     w, t, color);   /* bawah */
    fb_fill_rect(x,         y,         t, h, color);   /* kiri */
    fb_fill_rect(x+w-t,     y,         t, h, color);   /* kanan */
}

void fb_draw_line(uint32_t x0, uint32_t y0,
                  uint32_t x1, uint32_t y1, uint32_t color)
{
    /* Bresenham's line algorithm */
    int dx = (int)x1 - (int)x0;
    int dy = (int)y1 - (int)y0;
    int sx = dx > 0 ? 1 : -1;
    int sy = dy > 0 ? 1 : -1;
    dx = dx < 0 ? -dx : dx;
    dy = dy < 0 ? -dy : dy;

    int err = (dx > dy ? dx : -dy) / 2;
    uint32_t x = x0, y = y0;

    while (1) {
        fb_put_pixel(x, y, color);
        if (x == x1 && y == y1) break;
        int e2 = err;
        if (e2 > -dx) { err -= dy; x += sx; }
        if (e2 <  dy) { err += dx; y += sy; }
    }
}

void fb_fill_circle(uint32_t cx, uint32_t cy,
                    uint32_t r, uint32_t color)
{
    /* Midpoint circle algorithm */
    int x = 0, y = (int)r;
    int d = 1 - (int)r;

    while (x <= y) {
        fb_fill_rect(cx - x, cy - y, x * 2, 1, color);
        fb_fill_rect(cx - y, cy - x, y * 2, 1, color);
        fb_fill_rect(cx - x, cy + y, x * 2, 1, color);
        fb_fill_rect(cx - y, cy + x, y * 2, 1, color);

        if (d < 0) {
            d += 2 * x + 3;
        } else {
            d += 2 * (x - y) + 5;
            y--;
        }
        x++;
    }
}

void fb_fill_rounded_rect(uint32_t x, uint32_t y,
                           uint32_t w, uint32_t h,
                           uint32_t r, uint32_t color)
{
    /* Isi tengah */
    fb_fill_rect(x + r, y,     w - 2*r, h,     color);
    fb_fill_rect(x,     y + r, r,       h-2*r, color);
    fb_fill_rect(x+w-r, y + r, r,       h-2*r, color);

    /* Empat sudut dengan quarter-circle */
    uint32_t cx1 = x + r,     cy1 = y + r;
    uint32_t cx2 = x + w - r, cy2 = y + r;
    uint32_t cx3 = x + r,     cy3 = y + h - r;
    uint32_t cx4 = x + w - r, cy4 = y + h - r;

    int px = 0, py = (int)r, d = 1 - (int)r;
    while (px <= py) {
        /* Top-left */
        fb_fill_rect(cx1 - py, cy1 - px, py, 1, color);
        fb_fill_rect(cx1 - px, cy1 - py, px, 1, color);
        /* Top-right */
        fb_fill_rect(cx2,      cy2 - px, py, 1, color);
        fb_fill_rect(cx2,      cy2 - py, px, 1, color);
        /* Bottom-left */
        fb_fill_rect(cx3 - py, cy3 + px, py, 1, color);
        fb_fill_rect(cx3 - px, cy3 + py, px, 1, color);
        /* Bottom-right */
        fb_fill_rect(cx4,      cy4 + px, py, 1, color);
        fb_fill_rect(cx4,      cy4 + py, px, 1, color);

        if (d < 0) { d += 2*px+3; }
        else       { d += 2*(px-py)+5; py--; }
        px++;
    }
}

/* ─────────────────────────────────────────────
   Teks — render satu karakter dari bitmap font
   ───────────────────────────────────────────── */
void fb_draw_char(uint32_t x, uint32_t y,
                  char c, uint32_t fg, uint32_t bg)
{
    if (c < 32 || c > 127) c = '?';
    const uint8_t *glyph = font8x16[c - 32];

    for (uint32_t row = 0; row < FONT_H; row++) {
        uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < FONT_W; col++) {
            uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
            fb_put_pixel(x + col, y + row, color);
        }
    }
}

void fb_draw_string(uint32_t x, uint32_t y,
                    const char *str, uint32_t fg, uint32_t bg)
{
    while (*str) {
        fb_draw_char(x, y, *str++, fg, bg);
        x += FONT_W;
    }
}

void fb_draw_string_scaled(uint32_t x, uint32_t y,
                            const char *str,
                            uint32_t fg, uint32_t bg,
                            uint32_t scale)
{
    while (*str) {
        if (*str < 32 || *str > 127) { str++; x += FONT_W * scale; continue; }
        const uint8_t *glyph = font8x16[*str - 32];
        for (uint32_t row = 0; row < FONT_H; row++) {
            uint8_t bits = glyph[row];
            for (uint32_t col = 0; col < FONT_W; col++) {
                uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
                fb_fill_rect(x + col*scale, y + row*scale, scale, scale, color);
            }
        }
        x += FONT_W * scale;
        str++;
    }
}

/* ─────────────────────────────────────────────
   Console mode — teks scrolling seperti terminal
   ───────────────────────────────────────────── */
void fb_console_init(void) {
    con_x    = 0;
    con_y    = 0;
    con_cols = fb_w / FONT_W;
    con_rows = fb_h / FONT_H;
    con_fg   = LUNAR_FG;
    con_bg   = LUNAR_BG;
}

void fb_console_set_color(uint32_t fg, uint32_t bg) {
    con_fg = fg;
    con_bg = bg;
}

void fb_console_clear(void) {
    fb_clear(con_bg);
    con_x = 0;
    con_y = 0;
}

void fb_console_putc(char c) {
    if (c == '\n') {
        con_x = 0;
        con_y++;
    } else if (c == '\r') {
        con_x = 0;
    } else if (c == '\t') {
        con_x = (con_x + 4) & ~3;
    } else if (c == '\b') {
        if (con_x > 0) {
            con_x--;
            fb_draw_char(con_x * FONT_W, con_y * FONT_H, ' ', con_fg, con_bg);
        }
    } else {
        fb_draw_char(con_x * FONT_W, con_y * FONT_H, c, con_fg, con_bg);
        con_x++;
        if (con_x >= con_cols) { con_x = 0; con_y++; }
    }

    /* Scroll jika sampai bawah */
    if (con_y >= con_rows) {
        fb_scroll_up(1);
        con_y = con_rows - 1;
    }
}

void fb_console_puts(const char *str) {
    while (*str) fb_console_putc(*str++);
}